def earned_codes(finished: set[str]) -> list[str]:
    """Which achievement codes a learner with these finished items now holds."""
    units_done = sum(1 for k in UNIT_KEYS if k in finished)
    exercises_done = sum(1 for k in EXERCISE_KEYS if k in finished)
    out = []
    for badge in ACHIEVEMENTS:
        rule = badge["rule"]
        kind = rule["type"]
        if kind == "account":
            ok = True
        elif kind == "item":
            ok = rule["key"] in finished
        elif kind == "units":
            ok = units_done >= rule["count"]
        elif kind == "all_exercises":
            ok = exercises_done >= len(EXERCISE_KEYS)
        elif kind == "everything":
            ok = units_done >= len(UNIT_KEYS) and exercises_done >= len(EXERCISE_KEYS)
        else:
            ok = False
        if ok:
            out.append(badge["code"])
    return out


