_ANSWER_KEYS = ("answer", "answers", "correct", "order")


def public_exercise(exercise_id: str) -> dict:
    """One exercise with every answer key stripped out before it reaches a browser."""
    spec = EXERCISES[exercise_id]
    out = {}
    for key, value in spec.items():
        if key in _ANSWER_KEYS:
            continue
        if key in ("items", "sentences"):
            out[key] = [{k: v for k, v in item.items() if k not in _ANSWER_KEYS}
                        for item in value]
        elif key == "steps":
            out[key] = [dict(step) for step in value]
        else:
            out[key] = value
    return out


